const fs=require('fs');
const path=require('path');
(async()=>{
  const pages=await(await fetch('http://127.0.0.1:19293/json/list')).json();
  const target=pages.find(p=>p.title==='TFX Launcher');
  if(!target)throw Error('Installed application page not found');
  const ws=new WebSocket(target.webSocketDebuggerUrl);await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject;});
  let sequence=0;const pending=new Map();
  ws.onmessage=event=>{const message=JSON.parse(event.data);if(message.id){const p=pending.get(message.id);if(p){pending.delete(message.id);message.error?p.reject(Error(JSON.stringify(message.error))):p.resolve(message.result);}}};
  const call=(method,params={})=>new Promise((resolve,reject)=>{const id=++sequence;pending.set(id,{resolve,reject});ws.send(JSON.stringify({id,method,params}));});
  const evaluate=async expression=>{const r=await call('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw Error(JSON.stringify(r.exceptionDetails));return r.result.value;};
  const result={url:target.url};
  await evaluate(`Fold.setMode('northstar')`);
  await new Promise(r=>setTimeout(r,800));
  result.initial=await evaluate(`(()=>({title:document.title,version:document.querySelector('#launcherEditionVersion')?.textContent,aboutVersion:document.querySelector('#vpversion')?.textContent,mode:document.body.dataset.foldView,visibleElements:[...document.querySelectorAll('#nsMain *')].filter(e=>e.getBoundingClientRect().width>0&&e.getBoundingClientRect().height>0).length,bridge:typeof window.Fold}))()`);
  if(!result.initial.version.includes('1.1.0'))throw Error('UI version mismatch');
  if(result.initial.visibleElements<5)throw Error('Northstar page empty');
  await evaluate(`Fold.setMode('vanilla')`);
  await new Promise(r=>setTimeout(r,1200));
  result.vanilla=await evaluate(`(()=>({selected:settings.modProfileServer,view:document.body.dataset.foldView,contentDisplay:getComputedStyle(document.querySelector('#tfContent')).display,visibleElements:[...document.querySelectorAll('#tfContent *')].filter(e=>e.getBoundingClientRect().width>0&&e.getBoundingClientRect().height>0).length,launchVisible:document.querySelector('#playTfBtn').getBoundingClientRect().height>0}))()`);
  console.log(JSON.stringify(result,null,2));
  if(!result.vanilla.launchVisible||result.vanilla.visibleElements<5)throw Error('Vanilla page empty');
  await evaluate(`Fold.setMode('northstar')`);
  await new Promise(r=>setTimeout(r,800));
  result.northstarReturn=await evaluate(`({selected:settings.modProfileServer,launchVisible:document.querySelector('#playNsBtn').getBoundingClientRect().height>0})`);
  if(!result.northstarReturn.launchVisible)throw Error('Northstar return failed');
  result.eaServiceNotStarted=true;
  fs.writeFileSync(path.join(__dirname,'smoke.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));ws.close();
})().catch(e=>{console.error(e);process.exit(1);});
